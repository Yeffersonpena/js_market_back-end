ALTER VIEW [dbo].[VI_AVANCES_INFO_VENDEDOR] AS
SELECT DISTINCT 
    E.NOMBRE_RESPONSABLE,
    E.DNI_RESPONSABLE,
    E.NOMBRE_VENDEDOR1,
    F.ULTIMA_FECHA,
   -- E.CLUSTER_PDV_REGULAR,
	E.GRUPO AS 'CLUSTER_PDV_REGULAR',
   isnull(E.CELULAR_VENDEDOR,0) as 'CELULAR_VENDEDOR',
    E.CUOTA_PREPAGO,
	E.ACCION_2,
   
	 -- 
	(SELECT COUNT(*)
     FROM (
         SELECT DISTINCT *
         FROM dbo.PDV_OUT_FUNNEL
         WHERE DNI_RESPONSABLE = E.DNI_RESPONSABLE
           AND YEAR(fecha) = YEAR(GETDATE())
           AND MONTH(fecha) = MONTH(GETDATE())
           AND [RECARGAS>5] = 1
     ) AS SubQuery 
    ) AS RECARGA_TOTAL,





   -- (SELECT COUNT(*) 
    -- FROM dbo.PDV_OUT_FUNNEL 
    -- WHERE DNI_RESPONSABLE = E.DNI_RESPONSABLE 
      -- AND PRODUCTO_WEB IN ('PREPAGO M7', 'PORT PREPAGO M7')
	  -- AND YEAR(FECHA) = YEAR(GETDATE())
	  -- -- AND MONTH(FECHA) = MONTH(DATEADD(MONTH, -1, GETDATE()))
	  -- AND MONTH(FECHA) = MONTH(GETDATE())
	   ---
	 --
	 (SELECT
	 --COUNT(*) 
	 sum(cantidad)
	   FROM dbo.tbl_venta_log 
     WHERE DNI_RESPONSABLE = E.DNI_RESPONSABLE 
       AND YEAR(FECHA) = YEAR(GETDATE())
       AND MONTH(FECHA) = MONTH(GETDATE())
      -- AND PRODUCT_NAME = 'Prepago' 
       --AND OPERATION_NAME IN ('Alta', 'Portabilidad')
	 ) AS [AVANCE PREPAGO],

    CASE 
        WHEN E.ACCION_1 = 'PDV REGULAR' THEN 'PDV'
        ELSE E.ACCION_1
    END AS ACCION
FROM 
    dbo.PDV_OUT_ENTREGABLE E
JOIN 
    (SELECT DNI_RESPONSABLE, MAX(FECHA) AS ULTIMA_FECHA
     FROM dbo.PDV_OUT_FUNNEL
	   WHERE YEAR(FECHA) = YEAR(GETDATE()) 
     --  AND MONTH(FECHA) = MONTH(DATEADD(MONTH, -1, GETDATE()))
     GROUP BY DNI_RESPONSABLE) F
ON E.DNI_RESPONSABLE = F.DNI_RESPONSABLE;
GO


