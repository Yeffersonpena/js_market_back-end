CREATE VIEW [dbo].[VI_PDV_PAYMENT] AS
SELECT DISTINCT 
    E.NOMBRE_RESPONSABLE,
    E.DNI_RESPONSABLE,
    E.NOMBRE_VENDEDOR1,
    F.ULTIMA_FECHA,
    E.CLUSTER_PDV_REGULAR,
    E.CELULAR_VENDEDOR,
    E.CUOTA_PREPAGO,
    (SELECT COUNT(CASE WHEN [RECARGAS>5] = '1' THEN 1 END) 
     FROM dbo.PDV_OUT_FUNNEL 
     WHERE DNI_RESPONSABLE = E.DNI_RESPONSABLE) AS RECARGA_TOTAL,
    (SELECT COUNT(*) 
     FROM dbo.PDV_OUT_FUNNEL 
     WHERE DNI_RESPONSABLE = E.DNI_RESPONSABLE 
       AND PRODUCTO_WEB IN ('PREPAGO M7', 'PORT PREPAGO M7')) AS [AVANCE PREPAGO],
    CASE 
        WHEN E.ACCION_1 = 'PDV REGULAR' THEN 'PDV'
        ELSE E.ACCION_1
    END AS ACCION
FROM 
    dbo.PDV_OUT_ENTREGABLE E
JOIN 
    (SELECT DNI_RESPONSABLE, MAX(FECHA) AS ULTIMA_FECHA
     FROM dbo.PDV_OUT_FUNNEL
     GROUP BY DNI_RESPONSABLE) F
ON E.DNI_RESPONSABLE = F.DNI_RESPONSABLE;
GO
