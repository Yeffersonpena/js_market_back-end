-- =============================================
-- Tabla: PDV_VISITAS_AD_PROGRAMACION
-- Descripción: Almacena la programación mensual de visitas a PDVs AD (Tecnología y Telecom)
--              Una fila por cada PDV programado en un mes específico
-- Relación: Se relaciona con PDV_VISITAS_AD_DIAS (1:N) para los días específicos
-- =============================================
CREATE TABLE dbo.PDV_VISITAS_AD_PROGRAMACION (
    id INT IDENTITY(1,1) NOT NULL PRIMARY KEY,

    -- Identificadores y temporalidad
    DNI_RESPONSABLE INT NOT NULL,
    AÑO INT NOT NULL,
    MES INT NOT NULL,

    -- Datos del PDV (del Excel)
    CODIGO_CUM VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL, -- Código CUM del PDV (identificador alternativo)
    COD_CLIENTE VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL,
    ZONAL VARCHAR(70) COLLATE Modern_Spanish_CI_AS NULL,
    RUTA VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL,
    COD_VVDD INT NULL,
    MODULO VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL,
    NOMBRE_PUNTO VARCHAR(255) COLLATE Modern_Spanish_CI_AS NULL,
    CEDULA_CLIENTE VARCHAR(70) COLLATE Modern_Spanish_CI_AS NULL,
    DEPARTAMENTO VARCHAR(100) COLLATE Modern_Spanish_CI_AS NULL,
    PROVINCIA VARCHAR(100) COLLATE Modern_Spanish_CI_AS NULL,
    DISTRITO VARCHAR(100) COLLATE Modern_Spanish_CI_AS NULL,
    DIRECCION VARCHAR(500) COLLATE Modern_Spanish_CI_AS NULL,
    CONGLOMERADO VARCHAR(255) COLLATE Modern_Spanish_CI_AS NULL,
    LATITUD VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL, -- VARCHAR para preservar precisión exacta del Excel
    LONGITUD VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL, -- VARCHAR para preservar precisión exacta del Excel
    VENDEDORES VARCHAR(255) COLLATE Modern_Spanish_CI_AS NULL,

    -- Metadatos de la programación
    TIPO_VISITA VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL, -- TELEGESTION, PRESENCIAL
    FRECUENCIA VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL,   -- SEMANAL, QUINCENAL, MENSUAL
    STATUS VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL DEFAULT 'PROGRAMADO', -- PROGRAMADO, CANCELADO, etc.
    COMENTARIOS VARCHAR(MAX) COLLATE Modern_Spanish_CI_AS NULL,

    -- Auditoría
    FECHA_CREACION DATETIME NULL DEFAULT GETDATE(),
    USUARIO_CREACION VARCHAR(100) COLLATE Modern_Spanish_CI_AS NULL,
    FECHA_ACTUALIZACION DATETIME NULL,
    USUARIO_ACTUALIZACION VARCHAR(100) COLLATE Modern_Spanish_CI_AS NULL,

    -- Constraints
    CONSTRAINT UQ_PDV_VISITAS_AD_PROG_COD_CLIENTE_AÑO_MES
        UNIQUE (COD_CLIENTE, AÑO, MES),
    CONSTRAINT CHK_PDV_VISITAS_AD_PROG_AÑO
        CHECK (AÑO >= 2020 AND AÑO <= 2100),
    CONSTRAINT CHK_PDV_VISITAS_AD_PROG_MES
        CHECK (MES >= 1 AND MES <= 12)
);

-- Índices para optimizar consultas frecuentes
CREATE NONCLUSTERED INDEX IX_PDV_VISITAS_AD_PROG_COD_CLIENTE_AÑO_MES
    ON dbo.PDV_VISITAS_AD_PROGRAMACION (COD_CLIENTE ASC, AÑO ASC, MES ASC)
    WITH (PAD_INDEX = OFF, FILLFACTOR = 100, SORT_IN_TEMPDB = OFF,
          IGNORE_DUP_KEY = OFF, STATISTICS_NORECOMPUTE = OFF,
          ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON)
    ON [PRIMARY];

-- Índice adicional para consultas por DNI_RESPONSABLE (sin restricción UNIQUE)
CREATE NONCLUSTERED INDEX IX_PDV_VISITAS_AD_PROG_DNI_AÑO_MES
    ON dbo.PDV_VISITAS_AD_PROGRAMACION (DNI_RESPONSABLE ASC, AÑO ASC, MES ASC)
    WITH (PAD_INDEX = OFF, FILLFACTOR = 100, SORT_IN_TEMPDB = OFF,
          IGNORE_DUP_KEY = OFF, STATISTICS_NORECOMPUTE = OFF,
          ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON)
    ON [PRIMARY];

CREATE NONCLUSTERED INDEX IX_PDV_VISITAS_AD_PROG_VENDEDOR
    ON dbo.PDV_VISITAS_AD_PROGRAMACION (COD_VVDD ASC, AÑO ASC, MES ASC)
    INCLUDE (DNI_RESPONSABLE, NOMBRE_PUNTO, ZONAL, TIPO_VISITA)
    WITH (PAD_INDEX = OFF, FILLFACTOR = 100, SORT_IN_TEMPDB = OFF,
          IGNORE_DUP_KEY = OFF, STATISTICS_NORECOMPUTE = OFF,
          ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON)
    ON [PRIMARY];

CREATE NONCLUSTERED INDEX IX_PDV_VISITAS_AD_PROG_ZONAL
    ON dbo.PDV_VISITAS_AD_PROGRAMACION (ZONAL ASC, AÑO ASC, MES ASC)
    INCLUDE (DNI_RESPONSABLE, NOMBRE_PUNTO, COD_VVDD)
    WITH (PAD_INDEX = OFF, FILLFACTOR = 100, SORT_IN_TEMPDB = OFF,
          IGNORE_DUP_KEY = OFF, STATISTICS_NORECOMPUTE = OFF,
          ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON)
    ON [PRIMARY];

CREATE NONCLUSTERED INDEX IX_PDV_VISITAS_AD_PROG_STATUS
    ON dbo.PDV_VISITAS_AD_PROGRAMACION (STATUS ASC, AÑO ASC, MES ASC)
    WITH (PAD_INDEX = OFF, FILLFACTOR = 100, SORT_IN_TEMPDB = OFF,
          IGNORE_DUP_KEY = OFF, STATISTICS_NORECOMPUTE = OFF,
          ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON)
    ON [PRIMARY];

