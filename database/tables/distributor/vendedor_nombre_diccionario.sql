-- Diccionario de equivalencias de nombres de vendedor (JS vs YALI y variantes).
-- Base de datos: DISTRIBUTOR_DATAMART
-- Uso: normalizar nombre_alias (tras UPPER/TRIM en query) a nombre_canonico.
-- origen: referencia opcional (ej. JS, YALI, PROGRAMACION); texto libre, sin lista cerrada.

CREATE TABLE [DISTRIBUTOR_DATAMART].[dbo].[vendedor_nombre_diccionario] (
    id INT IDENTITY(1,1) NOT NULL,
    nombre_alias VARCHAR(200) COLLATE Modern_Spanish_CI_AS NOT NULL,
    nombre_canonico VARCHAR(200) COLLATE Modern_Spanish_CI_AS NOT NULL,
    origen VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL,
    activo BIT NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT GETDATE(),
    updated_at DATETIME NULL,
    CONSTRAINT PK_vendedor_nombre_diccionario PRIMARY KEY (id),
    CONSTRAINT UQ_vendedor_nombre_diccionario_alias UNIQUE (nombre_alias)
);

CREATE INDEX IX_vendedor_nombre_diccionario_canonico
ON [DISTRIBUTOR_DATAMART].[dbo].[vendedor_nombre_diccionario] (nombre_canonico, activo);

CREATE INDEX IX_vendedor_nombre_diccionario_activo
ON [DISTRIBUTOR_DATAMART].[dbo].[vendedor_nombre_diccionario] (activo);

