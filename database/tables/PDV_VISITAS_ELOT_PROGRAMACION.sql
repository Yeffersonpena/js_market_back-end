-- =============================================
-- Tabla: PDV_VISITAS_ELOT_PROGRAMACION
-- Descripción: Almacena la programación mensual de visitas a PDVs ELOT (Loterías)
--              Una fila por cada PDV ELOT programado en un mes específico
--              Programación por días de la semana (Lunes, Martes, etc.) no por fechas específicas
-- Relación: Se relaciona con PDV_VISITAS_ELOT_DIAS_SEMANA (1:N) para los días de semana
-- =============================================
CREATE TABLE ELOT.dbo.PDV_VISITAS_ELOT_PROGRAMACION (
    id INT IDENTITY(1,1) NOT NULL PRIMARY KEY,

    -- Identificadores y temporalidad
    DNI INT NOT NULL, -- Identificador del punto ELOT
    AÑO INT NOT NULL,
    MES INT NOT NULL,

    -- Datos del PDV ELOT (del Excel)
    COD_CLIENTE VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL,
    ID_ELOT VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL,
    ZONAL VARCHAR(70) COLLATE Modern_Spanish_CI_AS NULL,
    DISTRITO VARCHAR(100) COLLATE Modern_Spanish_CI_AS NULL,
    PROVINCIA VARCHAR(100) COLLATE Modern_Spanish_CI_AS NULL,
    DEPARTAMENTO VARCHAR(100) COLLATE Modern_Spanish_CI_AS NULL,
    RAZON_SOCIAL VARCHAR(255) COLLATE Modern_Spanish_CI_AS NULL,
    DIRECCION VARCHAR(500) COLLATE Modern_Spanish_CI_AS NULL,
    LATITUD DECIMAL(10,8) NULL,
    LONGITUD DECIMAL(11,8) NULL,
    TELEFONO VARCHAR(20) COLLATE Modern_Spanish_CI_AS NULL,
    COD_VVDD INT NULL,
    MODULO VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL,
    NEW_MODULO VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL,
    RUTA VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL,
    VENDEDOR VARCHAR(255) COLLATE Modern_Spanish_CI_AS NULL,

    -- Metadatos de la programación
    STATUS VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL DEFAULT 'PROGRAMADO', -- PROGRAMADO, AGENTE, BOTICA, POR IMPLEMENTAR, etc.
    STATUS_IMPLEMENTO VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL, -- IMPLEMENTADO, POR IMPLEMENTAR, etc.
    COMENTARIOS VARCHAR(MAX) COLLATE Modern_Spanish_CI_AS NULL,

    -- Auditoría
    FECHA_CREACION DATETIME NULL DEFAULT GETDATE(),
    USUARIO_CREACION VARCHAR(100) COLLATE Modern_Spanish_CI_AS NULL,
    FECHA_ACTUALIZACION DATETIME NULL,
    USUARIO_ACTUALIZACION VARCHAR(100) COLLATE Modern_Spanish_CI_AS NULL,

    -- Constraints
    CONSTRAINT UQ_PDV_VISITAS_ELOT_PROG_DNI_AÑO_MES
        UNIQUE (DNI, AÑO, MES),
    CONSTRAINT CHK_PDV_VISITAS_ELOT_PROG_AÑO
        CHECK (AÑO >= 2020 AND AÑO <= 2100),
    CONSTRAINT CHK_PDV_VISITAS_ELOT_PROG_MES
        CHECK (MES >= 1 AND MES <= 12)
);

-- Índices para optimizar consultas frecuentes
CREATE NONCLUSTERED INDEX IX_PDV_VISITAS_ELOT_PROG_DNI_AÑO_MES
    ON ELOT.dbo.PDV_VISITAS_ELOT_PROGRAMACION (DNI ASC, AÑO ASC, MES ASC)
    WITH (PAD_INDEX = OFF, FILLFACTOR = 100, SORT_IN_TEMPDB = OFF,
          IGNORE_DUP_KEY = OFF, STATISTICS_NORECOMPUTE = OFF,
          ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON)
    ON [PRIMARY];

CREATE NONCLUSTERED INDEX IX_PDV_VISITAS_ELOT_PROG_VENDEDOR
    ON ELOT.dbo.PDV_VISITAS_ELOT_PROGRAMACION (COD_VVDD ASC, AÑO ASC, MES ASC)
    INCLUDE (DNI, RAZON_SOCIAL, ZONAL, STATUS)
    WITH (PAD_INDEX = OFF, FILLFACTOR = 100, SORT_IN_TEMPDB = OFF,
          IGNORE_DUP_KEY = OFF, STATISTICS_NORECOMPUTE = OFF,
          ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON)
    ON [PRIMARY];

CREATE NONCLUSTERED INDEX IX_PDV_VISITAS_ELOT_PROG_ZONAL
    ON ELOT.dbo.PDV_VISITAS_ELOT_PROGRAMACION (ZONAL ASC, AÑO ASC, MES ASC)
    INCLUDE (DNI, RAZON_SOCIAL, COD_VVDD)
    WITH (PAD_INDEX = OFF, FILLFACTOR = 100, SORT_IN_TEMPDB = OFF,
          IGNORE_DUP_KEY = OFF, STATISTICS_NORECOMPUTE = OFF,
          ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON)
    ON [PRIMARY];

CREATE NONCLUSTERED INDEX IX_PDV_VISITAS_ELOT_PROG_STATUS
    ON ELOT.dbo.PDV_VISITAS_ELOT_PROGRAMACION (STATUS ASC, AÑO ASC, MES ASC)
    WITH (PAD_INDEX = OFF, FILLFACTOR = 100, SORT_IN_TEMPDB = OFF,
          IGNORE_DUP_KEY = OFF, STATISTICS_NORECOMPUTE = OFF,
          ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON)
    ON [PRIMARY];

