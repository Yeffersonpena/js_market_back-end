CREATE PROCEDURE [dbo].[spLoadFileEntregable_new]
	@dateLoadFile date
AS
BEGIN
    BEGIN TRY
		    DECLARE @año int, @mes int;

			select top(1) @año= AÑO, @mes=MES from dbo.TempEntregable_New;
            delete from dbo.PDV_OUT_ENTREGABLE where AÑO=@año and MES=@mes;
            
			INSERT INTO PDV_OUT_ENTREGABLE (
            AÑO,MES, SOCIO, ZONAL, DNI_RESPONSABLE, [DNI/CE], DNI_VENDEDOR,NOMBRE_RESPONSABLE, NOMBRE_VENDEDOR, NOMBRE_SUPERVISOR,
            ESTADO, FECHA_INICIO, FECHA_FIN, ACCION_1, ACCION_2, DISTRITO,CONGLOMERADO, NUMERO_RECARGADOR,CHIP_MM,COORDENADA_X,COORDENADA_Y,
            CLUSTER_PDV_REGULAR, NOMBRE_VENDEDOR1, TEAM_LIDER, TEAM_LIDER_FECHA_INICIO,TEAM_LIDER_FECHA_FIN, CUOTA_PREPAGO, CELULAR_VENDEDOR, [GRUPO],
			[FINANCIAMIENTO_SALDO],[FINANCIAMIENTO_CHIPS],[FINANCIAMIENTO_TOTAL],
            [DNI SUPERVISOR], [CCTA BANCARIA MM], [ENTIDAD BANCARIA MM], [DNI SI ES TERCERO MM],[NUM SUPERVISOR],
            [FINANCIAMIENTO SALDO AL 1Q], [FINANCIAMIENTO CHIPS AL 1Q], [TOTA FINANCIAMIENTO 1Q], [FINANCIAMIENTO SALDO AL 2Q], [FINANCIAMIENTO CHIPS AL 2Q],	
            [TOTA FINANCIAMIENTO 2Q], [RESPONSABLE_CREACION_PDV], [NOMBRE_RESPONSABLE_CREACION], [FINANCIAMIENTO_TOTAL_DEL_MES], [Provincia], [NUM_DE_DNI_VVDD],
            [DNI_VENDEDOR2], [NOMBRE_VENDEDOR2],[NO_GESTIONABLE], [RANGO]
            )
            select 
            [AÑO], [MES], [SOCIO], [ZONAL], [DNI_RESPONSABLE], [DNI_CE], [DNI_VENDEDOR], [NOMBRE_RESPONSABLE], [NOMBRE_VENDEDOR],[NOMBRE_SUPERVISOR],
            [ESTADO],[FECHA_INICIO],[FECHA_CESE], [ACCION_1], [ACCION_2], [DISTRITO], [CONGLOMERADO],[NUMERO_RECARGADOR], [CHIPS_MM], 
            [COORDENADA_X], [COORDENADA_Y],'',[VENDEDOR_ZONIFICADO],[ES_TEAM_LEADER],[TEAM_LIDER_FECHA_INICIO], [TEAM_LIDER_FECHA_FINAL],[CUOTA_PDV], [NUM_VVDD_PDV], [GRUPOS], 
            [FINANCIAMIENTO_SALDO_AL_1Q], [FINANCIAMIENTO_CHIPS_AL_1Q], [TOTAL_FINANCIAMIENTO_1Q], 
            [DNI_SUPERVISOR],[CCTA_BANCARIA], [ENTIDAD_BANCARIA], [DNI_SI_ES_TERCERO], [NUM_SUPERVISOR],
            [FINANCIAMIENTO_SALDO_AL_1Q],[FINANCIAMIENTO_CHIPS_AL_1Q],[TOTAL_FINANCIAMIENTO_1Q], 
            [FINANCIAMIENTO_SALDO_AL_2Q],[FINANCIAMIENTO_CHIPS_AL_2Q], [TOTAL_FINANCIAMIENTO_2Q], 
            '', '', [FINANCIAMIENTO_TOTAL_DEL_MES], [Provincia], [NUM_DE_DNI_VVDD],[DNI_VENDEDOR2], [NOMBRE_VENDEDOR2],[NO_GESTIONABLE], [RANGO]
            from dbo.TempEntregable_New;

			update dbo.PDV_OUT_ENTREGABLE set dateUpdateFile=@dateLoadFile where año=@año and mes=@mes;
            ----
			delete from dbo.tbl_history_entregable where AÑO=@año and MES=@mes and dateUpdateFile=@dateLoadFile;
			INSERT INTO dbo.tbl_history_entregable (
            AÑO,MES, SOCIO, ZONAL, DNI_RESPONSABLE, [DNI/CE], DNI_VENDEDOR,NOMBRE_RESPONSABLE, NOMBRE_VENDEDOR, NOMBRE_SUPERVISOR,
            ESTADO, FECHA_INICIO, FECHA_FIN, ACCION_1, ACCION_2, DISTRITO,CONGLOMERADO, NUMERO_RECARGADOR,CHIP_MM,COORDENADA_X,COORDENADA_Y,
			NOMBRE_VENDEDOR1, TEAM_LIDER, TEAM_LIDER_FECHA_INICIO,TEAM_LIDER_FECHA_FIN, CUOTA_PREPAGO, CELULAR_VENDEDOR, [GRUPO],
            [DNI SUPERVISOR], [CCTA BANCARIA MM], [ENTIDAD BANCARIA MM], [DNI SI ES TERCERO MM],[NUM SUPERVISOR],
            [FINANCIAMIENTO SALDO AL 1Q], [FINANCIAMIENTO CHIPS AL 1Q], [TOTA FINANCIAMIENTO 1Q], [FINANCIAMIENTO SALDO AL 2Q], [FINANCIAMIENTO CHIPS AL 2Q],	
            [TOTA FINANCIAMIENTO 2Q], [RESPONSABLE_CREACION_PDV], [NOMBRE_RESPONSABLE_CREACION], [FINANCIAMIENTO_TOTAL_DEL_MES], [Provincia], [dateUpdateFile],
            [NUM_DE_DNI_VVDD], [RANGO]
            )
            select 
            [AÑO], [MES], [SOCIO], [ZONAL], [DNI_RESPONSABLE], [DNI_CE], [DNI_VENDEDOR], [NOMBRE_RESPONSABLE], [NOMBRE_VENDEDOR],[NOMBRE_SUPERVISOR],
            [ESTADO],[FECHA_INICIO],[FECHA_CESE], [ACCION_1], [ACCION_2], [DISTRITO], [CONGLOMERADO],[NUMERO_RECARGADOR], [CHIPS_MM], 
            [COORDENADA_X], [COORDENADA_Y],
			[VENDEDOR_ZONIFICADO],[ES_TEAM_LEADER],[TEAM_LIDER_FECHA_INICIO], [TEAM_LIDER_FECHA_FINAL],[CUOTA_PDV], [NUM_VVDD_PDV], [GRUPOS],  
            [DNI_SUPERVISOR],[CCTA_BANCARIA], [ENTIDAD_BANCARIA], [DNI_SI_ES_TERCERO], [NUM_SUPERVISOR],
            [FINANCIAMIENTO_SALDO_AL_1Q],[FINANCIAMIENTO_CHIPS_AL_1Q],[TOTAL_FINANCIAMIENTO_1Q], 
            [FINANCIAMIENTO_SALDO_AL_2Q],[FINANCIAMIENTO_CHIPS_AL_2Q], [TOTAL_FINANCIAMIENTO_2Q], 
            '', '', [FINANCIAMIENTO_TOTAL_DEL_MES], [Provincia], @dateLoadFile as dateUpdateFile, [NUM_DE_DNI_VVDD], [RANGO]
            from dbo.TempEntregable_New;
			UPDATE dbo.PDV_OUT_ENTREGABLE SET PDV_OUT_ENTREGABLE.ZONAL = ZM.ZONAL
			FROM dbo.PDV_OUT_ENTREGABLE AS EN
			JOIN PORTAL_COMERCIAL.dbo.PDV_OUT_MAESTRA_ZONAL AS ZM
				ON EN.AÑO = ZM.AÑO AND EN.MES = ZM.MES
				AND REPLACE(EN.ZONAL, ' ', '') = REPLACE(ZM.ZONAL, ' ', '')  
			WHERE EN.AÑO = @año AND EN.MES = @mes
			  AND EN.ZONAL != ZM.ZONAL;
			----
			--delete from dbo.TempEntregable_New;
			----
            exec dbo.paRegistrarUsuariosMasivo;
			exec sp_Sincronizar_Flyers @año,@mes;
            insert into dbo.tbl_log_procedimientos values ('spLoadFileEntregable_new', GETDATE());
        RETURN 0; 
    END TRY
    BEGIN CATCH
        RETURN ERROR_MESSAGE();  
    END CATCH
END
