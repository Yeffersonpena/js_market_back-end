CREATE PROCEDURE dbo.sp_Esquema_PDV_Premium
@año int,@mes int
AS 
;WITH VendedoresEntregable AS (
    SELECT DISTINCT 
        DNI_RESPONSABLE,
        NOMBRE_RESPONSABLE,
        DNI_VENDEDOR,
        NOMBRE_VENDEDOR ,
        NULLIF(DNI_VENDEDOR2, 0) AS DNI_VENDEDOR2,
        NOMBRE_VENDEDOR2 ,
        ZONAL 
    FROM PORTAL_COMERCIAL.dbo.PDV_OUT_ENTREGABLE
    WHERE AÑO = @año AND MES = @mes  
      AND ACCION_1 = 'PDV PREMIUM'
      AND ACCION_2 like 'PDV PREMIUM CON%'
),

EventosCombinados AS (
    -- Ventas
    SELECT DNI_RESPONSABLE, DNI_VENDEDOR AS DNI_EJECUTOR, 'VENTA' AS TIPO_EVENTO
    FROM PORTAL_COMERCIAL.dbo.VentasLog
    WHERE YEAR(FECHA) = @año AND MONTH(FECHA) = @mes AND PRODUCT_NAME = 'Prepago'
    UNION ALL
    SELECT DNI_RESPONSABLE, DNI_VENDEDOR AS DNI_EJECUTOR, 'PRE_PORTA' AS TIPO_EVENTO
    FROM PORTAL_COMERCIAL.dbo.VentasLog
    WHERE YEAR(FECHA) = @año AND MONTH(FECHA) = @mes AND PRODUCT_NAME = 'Prepago' AND OPERATION_NAME='Portabilidad'
    UNION ALL
    -- Recargas
    SELECT DNI_RESPONSABLE, DNI_VENDEDOR AS DNI_EJECUTOR, 'RECARGA' AS TIPO_EVENTO
    FROM PORTAL_COMERCIAL.dbo.PDV_OUT_FUNNEL
    WHERE YEAR(fecha) = @año AND MONTH(fecha) = @mes AND RECARGA_SI_NO = 1 AND [RECARGAS>5] = 1 AND PRODUCTO_WEB IN ('PREPAGO M7', 'PORT PREPAGO M7')
    UNION ALL
    -- Ventas de Calidad
    SELECT DNI_RESPONSABLE, DNI_VENDEDOR AS DNI_EJECUTOR, 'VENTA_CALIDAD' AS TIPO_EVENTO
    FROM PORTAL_COMERCIAL.dbo.PDV_OUT_FUNNEL
    WHERE YEAR(fecha) = @año AND MONTH(fecha) = @mes AND CALIDAD_CLUSTER IN ('Cluster 1: IMEI nuevo', 'Cluster 2: IMEI reutilizado')
    
    -- >>> NUEVO: PORTABILIDADES PREPAGO <<<
    UNION ALL
    SELECT DNI_RESPONSABLE, DNI_VENDEDOR AS DNI_EJECUTOR, 'PORTA_PRE' AS TIPO_EVENTO
    FROM PORTAL_COMERCIAL.dbo.PDV_OUT_FUNNEL
    WHERE YEAR(fecha) = @año AND MONTH(fecha) = @mes AND DNI_RESPONSABLE IS NOT NULL
      AND PRODUCTOORIGEN = 'PREPAGO' AND PRODUCTO_WEB = 'PORT M4 NO DIR'

    -- >>> NUEVO: PORTABILIDADES POSTPAGO <<<
    UNION ALL
    SELECT DNI_RESPONSABLE, DNI_VENDEDOR AS DNI_EJECUTOR, 'PORTA_POS' AS TIPO_EVENTO
    FROM PORTAL_COMERCIAL.dbo.PDV_OUT_FUNNEL
    WHERE YEAR(fecha) = @año AND MONTH(fecha) = @mes AND DNI_RESPONSABLE IS NOT NULL
      AND PRODUCTOORIGEN = 'POSTPAGO' AND PRODUCTO_WEB = 'PORT M4 NO DIR'
),
EventosDistribuidos AS (
    SELECT 
        v.DNI_RESPONSABLE,
        v.NOMBRE_RESPONSABLE,
        v.DNI_VENDEDOR,
        v.NOMBRE_VENDEDOR ,
        v.DNI_VENDEDOR2,
        v.NOMBRE_VENDEDOR2 , v.ZONAL, e.TIPO_EVENTO,
        CASE 
            WHEN e.DNI_EJECUTOR = v.DNI_VENDEDOR THEN 'VENDEDOR1'
            WHEN e.DNI_EJECUTOR = v.DNI_VENDEDOR2 THEN 'VENDEDOR2'
            ELSE 'RESPONSABLE'
        END AS TIPO_ACTOR
    FROM VendedoresEntregable v
    INNER JOIN EventosCombinados e ON v.DNI_RESPONSABLE = e.DNI_RESPONSABLE
),
MetricasAgregadas AS (
    SELECT 
        DNI_RESPONSABLE,
        NOMBRE_RESPONSABLE,
        DNI_VENDEDOR AS VVDD1,
        NOMBRE_VENDEDOR,
        DNI_VENDEDOR2 AS VVDD2,
        NOMBRE_VENDEDOR2,
        ZONAL,
        -- Conteos existentes...
        SUM(CASE WHEN TIPO_ACTOR = 'RESPONSABLE' AND TIPO_EVENTO = 'VENTA' THEN 1 ELSE 0 END) AS VENTAS_RESPONSABLE,
        SUM(CASE WHEN TIPO_ACTOR = 'VENDEDOR1' AND TIPO_EVENTO = 'VENTA' THEN 1 ELSE 0 END) AS VENTAS_VVDD1,
        SUM(CASE WHEN TIPO_ACTOR = 'VENDEDOR2' AND TIPO_EVENTO = 'VENTA' THEN 1 ELSE 0 END) AS VENTAS_VVDD2,
        SUM(CASE WHEN TIPO_ACTOR = 'RESPONSABLE' AND TIPO_EVENTO = 'RECARGA' THEN 1 ELSE 0 END) AS RECARGAS_RESPONSABLE,
        SUM(CASE WHEN TIPO_ACTOR = 'VENDEDOR1' AND TIPO_EVENTO = 'RECARGA' THEN 1 ELSE 0 END) AS RECARGAS_VVDD1,
        SUM(CASE WHEN TIPO_ACTOR = 'VENDEDOR2' AND TIPO_EVENTO = 'RECARGA' THEN 1 ELSE 0 END) AS RECARGAS_VVDD2,
        SUM(CASE WHEN TIPO_ACTOR = 'RESPONSABLE' AND TIPO_EVENTO = 'VENTA_CALIDAD' THEN 1 ELSE 0 END) AS VCALIDAD_RESPONSABLE,
        SUM(CASE WHEN TIPO_ACTOR = 'VENDEDOR1' AND TIPO_EVENTO = 'VENTA_CALIDAD' THEN 1 ELSE 0 END) AS VCALIDAD_VVDD1,
        SUM(CASE WHEN TIPO_ACTOR = 'VENDEDOR2' AND TIPO_EVENTO = 'VENTA_CALIDAD' THEN 1 ELSE 0 END) AS VCALIDAD_VVDD2,

        -- >>> NUEVO: CONTEO DE PORTABILIDADES <<<
        SUM(CASE WHEN TIPO_ACTOR = 'RESPONSABLE' AND TIPO_EVENTO = 'PRE_PORTA' THEN 1 ELSE 0 END) AS PRE_PORTA_RESPONSABLE,
        SUM(CASE WHEN TIPO_ACTOR = 'VENDEDOR1' AND TIPO_EVENTO = 'PRE_PORTA' THEN 1 ELSE 0 END) AS PRE_PORTA_VVDD1,
        SUM(CASE WHEN TIPO_ACTOR = 'VENDEDOR2' AND TIPO_EVENTO = 'PRE_PORTA' THEN 1 ELSE 0 END) AS PRE_PORTA_VVDD2,
        
        SUM(CASE WHEN TIPO_ACTOR = 'RESPONSABLE' AND TIPO_EVENTO = 'PORTA_PRE' THEN 1 ELSE 0 END) AS PORTAPRE_RESPONSABLE,
        SUM(CASE WHEN TIPO_ACTOR = 'VENDEDOR1' AND TIPO_EVENTO = 'PORTA_PRE' THEN 1 ELSE 0 END) AS PORTAPRE_VVDD1,
        SUM(CASE WHEN TIPO_ACTOR = 'VENDEDOR2' AND TIPO_EVENTO = 'PORTA_PRE' THEN 1 ELSE 0 END) AS PORTAPRE_VVDD2,
        SUM(CASE WHEN TIPO_ACTOR = 'RESPONSABLE' AND TIPO_EVENTO = 'PORTA_POS' THEN 1 ELSE 0 END) AS PORTAPOS_RESPONSABLE,
        SUM(CASE WHEN TIPO_ACTOR = 'VENDEDOR1' AND TIPO_EVENTO = 'PORTA_POS' THEN 1 ELSE 0 END) AS PORTAPOS_VVDD1,
        SUM(CASE WHEN TIPO_ACTOR = 'VENDEDOR2' AND TIPO_EVENTO = 'PORTA_POS' THEN 1 ELSE 0 END) AS PORTAPOS_VVDD2,
        
        -- Totales de equipo
        SUM(CASE WHEN TIPO_EVENTO = 'VENTA' THEN 1 ELSE 0 END) AS TOTAL_VENTAS,
        SUM(CASE WHEN TIPO_EVENTO = 'RECARGA' THEN 1 ELSE 0 END) AS TOTAL_RECARGAS,
        SUM(CASE WHEN TIPO_EVENTO = 'VENTA_CALIDAD' THEN 1 ELSE 0 END) AS TOTAL_VCALIDAD

    FROM EventosDistribuidos
    GROUP BY DNI_RESPONSABLE,
        NOMBRE_RESPONSABLE,
        DNI_VENDEDOR,
        NOMBRE_VENDEDOR,
        DNI_VENDEDOR2,
        NOMBRE_VENDEDOR2,
        ZONAL
)
SELECT
    m.DNI_RESPONSABLE,m.NOMBRE_RESPONSABLE, m.VVDD1,m.NOMBRE_VENDEDOR, 
    m.VVDD2, m.NOMBRE_VENDEDOR2, m.ZONAL,
    m.VENTAS_RESPONSABLE, m.VENTAS_VVDD1, m.VENTAS_VVDD2,
    m.RECARGAS_RESPONSABLE, m.RECARGAS_VVDD1, m.RECARGAS_VVDD2,
    m.VCALIDAD_RESPONSABLE, m.VCALIDAD_VVDD1, m.VCALIDAD_VVDD2,

    -- >>> NUEVO: COLUMNAS DE PORTABILIDADES EN EL RESULTADO FINAL <<<
    m.PRE_PORTA_RESPONSABLE, m.PRE_PORTA_VVDD1, m.PRE_PORTA_VVDD2,
    m.PORTAPRE_RESPONSABLE, m.PORTAPRE_VVDD1, m.PORTAPRE_VVDD2,
    m.PORTAPOS_RESPONSABLE, m.PORTAPOS_VVDD1, m.PORTAPOS_VVDD2,
    
    -- Columnas de totales y cálculos finales
    m.TOTAL_VENTAS, m.TOTAL_RECARGAS, m.TOTAL_VCALIDAD,
    COALESCE((CAST(m.TOTAL_RECARGAS AS DECIMAL(10,2)) * 100) / NULLIF(m.TOTAL_VENTAS, 0), 0) AS RATIO_EQUIPO,
    dbo.fn_CalcularBonoUnitario(
        'PDV PREMIUM',
        m.ZONAL,
        m.TOTAL_VENTAS,
        COALESCE((CAST(m.TOTAL_RECARGAS AS DECIMAL(10,2)) * 100) / NULLIF(m.TOTAL_VENTAS, 0), 0),
        m.TOTAL_VCALIDAD,
        @año,
        @mes
    ) AS BONO_UNITARIO_EQUIPO
FROM MetricasAgregadas m
ORDER BY m.ZONAL, m.DNI_RESPONSABLE;