CREATE PROCEDURE dbo.sp_Esquema_PDV_Premium_Sin_HC
@año int,@mes int
AS 
;WITH ResponsablesEntregable AS (
    SELECT DISTINCT 
        DNI_RESPONSABLE,
        NOMBRE_RESPONSABLE,
        ZONAL 
    FROM PORTAL_COMERCIAL.dbo.PDV_OUT_ENTREGABLE
    WHERE AÑO = @año AND MES = @mes  
      AND ACCION_1 = 'PDV PREMIUM'
      AND ACCION_2 like 'PDV PREMIUM SIN%'
),

-- CTE para calcular días únicos de ventas por responsable (equipo completo)
DiasVentasResponsable AS (
    SELECT 
        DNI_RESPONSABLE,
        COUNT(DISTINCT CAST(FECHA AS DATE)) AS DIAS_VENTAS_RESPONSABLE
    FROM PORTAL_COMERCIAL.dbo.VentasLog
    WHERE YEAR(FECHA) = @año AND MONTH(FECHA) = @mes 
      AND PRODUCT_NAME = 'Prepago'
      AND DNI_RESPONSABLE IS NOT NULL
    GROUP BY DNI_RESPONSABLE
),

-- CTE para calcular ventas del mes anterior
VentasMesAnterior AS (
    SELECT 
        DNI_RESPONSABLE,
        COUNT(*) AS VENTAS_MES_ANTERIOR
    FROM PORTAL_COMERCIAL.dbo.VentasLog
    WHERE (
        -- Caso normal: mes anterior del mismo año
        (@mes > 1 AND YEAR(FECHA) = @año AND MONTH(FECHA) = @mes - 1)
        OR 
        -- Caso especial: enero toma diciembre del año anterior
        (@mes = 1 AND YEAR(FECHA) = @año - 1 AND MONTH(FECHA) = 12)
    )
      AND PRODUCT_NAME = 'Prepago'
      AND DNI_RESPONSABLE IS NOT NULL
    GROUP BY DNI_RESPONSABLE
),

EventosCombinados AS (
    -- Ventas
    SELECT DNI_RESPONSABLE, DNI_VENDEDOR AS DNI_EJECUTOR, 'VENTA' AS TIPO_EVENTO
    FROM PORTAL_COMERCIAL.dbo.VentasLog
    WHERE YEAR(FECHA) = @año AND MONTH(FECHA) = @mes AND PRODUCT_NAME = 'Prepago'
    UNION ALL
    SELECT DNI_RESPONSABLE, DNI_VENDEDOR AS DNI_EJECUTOR, 'PRE_PORTA' AS TIPO_EVENTO
    FROM PORTAL_COMERCIAL.dbo.VentasLog
    WHERE YEAR(FECHA) = @año AND MONTH(FECHA) = @mes AND PRODUCT_NAME = 'Prepago' AND OPERATION_NAME='Portabilidad'
    UNION ALL
    -- Recargas
    SELECT DNI_RESPONSABLE, DNI_VENDEDOR AS DNI_EJECUTOR, 'RECARGA' AS TIPO_EVENTO
    FROM PORTAL_COMERCIAL.dbo.PDV_OUT_FUNNEL
    WHERE YEAR(fecha) = @año AND MONTH(fecha) = @mes AND RECARGA_SI_NO = 1 AND [RECARGAS>5] = 1 AND PRODUCTO_WEB IN ('PREPAGO M7', 'PORT PREPAGO M7')
    UNION ALL
    -- Ventas de Calidad
    SELECT DNI_RESPONSABLE, DNI_VENDEDOR AS DNI_EJECUTOR, 'VENTA_CALIDAD' AS TIPO_EVENTO
    FROM PORTAL_COMERCIAL.dbo.PDV_OUT_FUNNEL
    WHERE YEAR(fecha) = @año AND MONTH(fecha) = @mes AND CALIDAD_CLUSTER IN ('Cluster 1: IMEI nuevo', 'Cluster 2: IMEI reutilizado')
    
    -- >>> NUEVO: PORTABILIDADES PREPAGO <<<
    UNION ALL
    SELECT DNI_RESPONSABLE, DNI_VENDEDOR AS DNI_EJECUTOR, 'PORTA_PRE' AS TIPO_EVENTO
    FROM PORTAL_COMERCIAL.dbo.PDV_OUT_FUNNEL
    WHERE YEAR(fecha) = @año AND MONTH(fecha) = @mes AND DNI_RESPONSABLE IS NOT NULL
      AND PRODUCTOORIGEN = 'PREPAGO' AND PRODUCTO_WEB = 'PORT M4 NO DIR'

    -- >>> NUEVO: PORTABILIDADES POSTPAGO <<<
    UNION ALL
    SELECT DNI_RESPONSABLE, DNI_VENDEDOR AS DNI_EJECUTOR, 'PORTA_POS' AS TIPO_EVENTO
    FROM PORTAL_COMERCIAL.dbo.PDV_OUT_FUNNEL
    WHERE YEAR(fecha) = @año AND MONTH(fecha) = @mes AND DNI_RESPONSABLE IS NOT NULL
      AND PRODUCTOORIGEN = 'POSTPAGO' AND PRODUCTO_WEB = 'PORT M4 NO DIR'
),
EventosDistribuidos AS (
    SELECT 
        r.DNI_RESPONSABLE,
        r.NOMBRE_RESPONSABLE,
        r.ZONAL, 
        e.TIPO_EVENTO,
        -- En PDV Premium Sin HC, todo se atribuye al responsable
        'RESPONSABLE' AS TIPO_ACTOR
    FROM ResponsablesEntregable r
    INNER JOIN EventosCombinados e ON r.DNI_RESPONSABLE = e.DNI_RESPONSABLE
),
MetricasAgregadas AS (
    SELECT 
        e.DNI_RESPONSABLE,
        e.NOMBRE_RESPONSABLE,
        e.ZONAL,
        -- Solo responsable tiene valores
        SUM(CASE WHEN e.TIPO_ACTOR = 'RESPONSABLE' AND e.TIPO_EVENTO = 'VENTA' THEN 1 ELSE 0 END) AS VENTAS_RESPONSABLE,
        SUM(CASE WHEN e.TIPO_ACTOR = 'RESPONSABLE' AND e.TIPO_EVENTO = 'RECARGA' THEN 1 ELSE 0 END) AS RECARGAS_RESPONSABLE,
        SUM(CASE WHEN e.TIPO_ACTOR = 'RESPONSABLE' AND e.TIPO_EVENTO = 'VENTA_CALIDAD' THEN 1 ELSE 0 END) AS VCALIDAD_RESPONSABLE,

        -- >>> CONTEO DE PORTABILIDADES <<<
        SUM(CASE WHEN e.TIPO_ACTOR = 'RESPONSABLE' AND e.TIPO_EVENTO = 'PRE_PORTA' THEN 1 ELSE 0 END) AS PRE_PORTA_RESPONSABLE,
        SUM(CASE WHEN e.TIPO_ACTOR = 'RESPONSABLE' AND e.TIPO_EVENTO = 'PORTA_PRE' THEN 1 ELSE 0 END) AS PORTAPRE_RESPONSABLE,
        SUM(CASE WHEN e.TIPO_ACTOR = 'RESPONSABLE' AND e.TIPO_EVENTO = 'PORTA_POS' THEN 1 ELSE 0 END) AS PORTAPOS_RESPONSABLE,
        
        -- >>> DÍAS DE VENTAS DEL RESPONSABLE (EQUIPO COMPLETO) <<<
        COALESCE(d.DIAS_VENTAS_RESPONSABLE, 0) AS DIAS_VENTAS_RESPONSABLE,
        
        -- >>> VENTAS DEL MES ANTERIOR <<<
        COALESCE(v.VENTAS_MES_ANTERIOR, 0) AS VENTAS_MES_ANTERIOR,
        
        -- Totales de equipo
        SUM(CASE WHEN e.TIPO_EVENTO = 'VENTA' THEN 1 ELSE 0 END) AS TOTAL_VENTAS,
        SUM(CASE WHEN e.TIPO_EVENTO = 'RECARGA' THEN 1 ELSE 0 END) AS TOTAL_RECARGAS,
        SUM(CASE WHEN e.TIPO_EVENTO = 'VENTA_CALIDAD' THEN 1 ELSE 0 END) AS TOTAL_VCALIDAD

    FROM EventosDistribuidos e
    LEFT JOIN DiasVentasResponsable d ON e.DNI_RESPONSABLE = d.DNI_RESPONSABLE
    LEFT JOIN VentasMesAnterior v ON e.DNI_RESPONSABLE = v.DNI_RESPONSABLE
    GROUP BY e.DNI_RESPONSABLE,
        e.NOMBRE_RESPONSABLE,
        e.ZONAL,
        d.DIAS_VENTAS_RESPONSABLE,
        v.VENTAS_MES_ANTERIOR
)
SELECT
    m.DNI_RESPONSABLE,
    m.NOMBRE_RESPONSABLE, 
    m.ZONAL,
    m.VENTAS_RESPONSABLE,
    m.RECARGAS_RESPONSABLE,
    m.VCALIDAD_RESPONSABLE,

    -- >>> COLUMNAS DE PORTABILIDADES EN EL RESULTADO FINAL <<<
    m.PRE_PORTA_RESPONSABLE,
    m.PORTAPRE_RESPONSABLE,
    m.PORTAPOS_RESPONSABLE,
    
    -- >>> DÍAS DE VENTAS DEL RESPONSABLE (EQUIPO COMPLETO) <<<
    m.DIAS_VENTAS_RESPONSABLE,
    
    -- >>> VENTAS DEL MES ANTERIOR <<<
    m.VENTAS_MES_ANTERIOR,
    
    -- Columnas de totales y cálculos finales
    m.TOTAL_VENTAS, m.TOTAL_RECARGAS, m.TOTAL_VCALIDAD,
    COALESCE((CAST(m.TOTAL_RECARGAS AS DECIMAL(10,2)) * 100) / NULLIF(m.TOTAL_VENTAS, 0), 0) AS RATIO_EQUIPO,
    dbo.fn_CalcularBonoUnitario_PDV(
        'PDV PREMIUM SIN HC',
        m.ZONAL,
        m.TOTAL_VENTAS,
        COALESCE((CAST(m.TOTAL_RECARGAS AS DECIMAL(10,2)) * 100) / NULLIF(m.TOTAL_VENTAS, 0), 0),
        m.TOTAL_VCALIDAD,
        @año,
        @mes
    ) AS BONO_UNITARIO_EQUIPO
FROM MetricasAgregadas m
ORDER BY m.ZONAL, m.DNI_RESPONSABLE;
